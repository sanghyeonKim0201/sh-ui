#!/usr/bin/env node
/**
 * registry 컴포넌트의 plain/tailwind/css-modules 변종 소스를
 * 빌드 타임에 한 번 읽어 `lib/variants.generated.ts` 로 emit.
 *
 * 이 단계가 필요한 이유: VariantSource 컴포넌트가 client component 페이지
 * (예: pagination, page-toc 등) 에서도 사용되므로 런타임 `node:fs` import 불가.
 * 컴포넌트가 합성 가능한 정적 데이터로 변종을 가져올 수 있게 해 준다.
 *
 * 실행: pnpm generate:variants  (build/dev 전 자동으로 호출됨)
 */
import { existsSync } from "node:fs";
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REGISTRY_ROOT = resolve(__dirname, "../../../packages/registry/react/components");
const OUT_PATH = resolve(__dirname, "../lib/variants.generated.ts");

const VARIANTS = {
  plain: [
    { filename: "index.tsx", src: "index.tsx", language: "tsx" },
    { filename: "styles.css", src: "styles.css", language: "css" },
  ],
  tailwind: [
    { filename: "index.tsx", src: "index.tailwind.tsx", language: "tsx" },
  ],
  "css-modules": [
    { filename: "index.tsx", src: "index.module.tsx", language: "tsx" },
    { filename: "styles.module.css", src: "styles.module.css", language: "css" },
  ],
  "vanilla-extract": [
    { filename: "index.tsx", src: "index.vanilla-extract.tsx", language: "tsx" },
    { filename: "styles.css.ts", src: "styles.css.ts", language: "tsx" },
  ],
};

async function loadComponent(name) {
  const out = {};
  for (const [fw, files] of Object.entries(VARIANTS)) {
    const loaded = [];
    for (const f of files) {
      const abs = resolve(REGISTRY_ROOT, name, f.src);
      if (!existsSync(abs)) continue;
      const code = await readFile(abs, "utf8");
      loaded.push({ filename: f.filename, code, language: f.language });
    }
    if (loaded.length > 0) out[fw] = loaded;
  }
  return out;
}

const entries = await readdir(REGISTRY_ROOT, { withFileTypes: true });
const components = entries.filter((e) => e.isDirectory()).map((e) => e.name).sort();

const result = {};
for (const name of components) {
  const data = await loadComponent(name);
  if (Object.keys(data).length > 0) result[name] = data;
}

await mkdir(dirname(OUT_PATH), { recursive: true });

const header = `// AUTO-GENERATED by scripts/generate-variants.mjs — do not edit directly.
// 각 컴포넌트의 plain/tailwind/css-modules 변종 소스를 정적으로 박아 client component
// 에서도 fs 없이 표시 가능하도록 한다.

export type FrameworkKey = "plain" | "tailwind" | "css-modules" | "vanilla-extract";

export interface VariantFile {
  filename: string;
  code: string;
  language: "tsx" | "css";
}

export type ComponentVariants = Partial<Record<FrameworkKey, VariantFile[]>>;

export const VARIANTS: Record<string, ComponentVariants> = ${JSON.stringify(result, null, 2)};
`;

await writeFile(OUT_PATH, header, "utf8");
console.log(`✓ ${Object.keys(result).length}개 컴포넌트 변종 → ${OUT_PATH}`);
