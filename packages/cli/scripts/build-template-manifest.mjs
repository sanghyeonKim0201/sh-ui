#!/usr/bin/env node
// 템플릿 디렉토리(`packages/cli/templates/`) 를 스캔해 파일 경로 manifest 를
// `packages/cli/src/create/templateManifest.js` 로 emit.
//
// describeTemplate() 가 이 manifest 를 읽어 "옵션 조합 → 생성될 파일 트리" 를
// 계산. fs 없이 동작해야 하므로 (브라우저 — apps/docs 의 CreateProjectDialog
// 가 sh-ui-cli/api 로 import) 정적 JS 모듈로 미리 박아둔다.
//
// 실행 시점:
//   - 템플릿 파일 추가/삭제 시 수동 (`pnpm --filter sh-ui-cli build:manifest`)
//   - pretest / prepublishOnly 에서 자동 (drift 방지)

import { readdir, stat, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const CLI_ROOT = resolve(__dirname, "..");
const TEMPLATES = resolve(CLI_ROOT, "templates");
const OUT = resolve(CLI_ROOT, "src", "create", "templateManifest.js");

/** 재귀로 디렉토리 모든 파일 경로를 root 기준 상대경로(POSIX) 로 반환. */
async function listFiles(root) {
  const out = [];
  async function walk(dir) {
    const entries = await readdir(dir, { withFileTypes: true });
    for (const entry of entries) {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) {
        await walk(full);
      } else if (entry.isFile()) {
        out.push(relative(root, full).split(sep).join("/"));
      }
    }
  }
  await walk(root);
  return out.sort();
}

/** _arch/ 하위가 아닌 (arch-neutral) 파일만. */
function filterBase(files) {
  return files.filter((p) => !p.startsWith("_arch/"));
}

/** _arch/<name>/ 하위 파일만, name prefix 제거 후 반환. */
function filterArch(files, archName) {
  const prefix = `_arch/${archName}/`;
  return files
    .filter((p) => p.startsWith(prefix))
    .map((p) => p.slice(prefix.length));
}

async function exists(p) {
  try {
    await stat(p);
    return true;
  } catch {
    return false;
  }
}

async function buildEntry(templateDir) {
  const all = await listFiles(templateDir);
  const archRoot = join(templateDir, "_arch");
  const hasArch = await exists(archRoot);
  if (!hasArch) {
    return { base: all };
  }
  const archDirs = (await readdir(archRoot, { withFileTypes: true }))
    .filter((e) => e.isDirectory())
    .map((e) => e.name);
  const arches = {};
  for (const name of archDirs) {
    arches[name] = filterArch(all, name);
  }
  return { base: filterBase(all), arches };
}

async function main() {
  const templateNames = (await readdir(TEMPLATES, { withFileTypes: true }))
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();

  const manifest = {};
  for (const name of templateNames) {
    manifest[name] = await buildEntry(join(TEMPLATES, name));
  }

  const banner =
    "// AUTO-GENERATED by scripts/build-template-manifest.mjs — do not edit by hand.\n" +
    "// 템플릿 디렉토리(`packages/cli/templates/`) 의 파일 경로 인덱스.\n" +
    "// describeTemplate() 의 입력. 템플릿 변경 후에는 빌드 스크립트 재실행 필요.\n\n";

  const body = `export const TEMPLATE_MANIFEST = ${JSON.stringify(manifest, null, 2)};\n`;

  await writeFile(OUT, banner + body);

  const totalFiles = Object.values(manifest).reduce((n, entry) => {
    let c = entry.base.length;
    if (entry.arches) {
      for (const arr of Object.values(entry.arches)) c += arr.length;
    }
    return n + c;
  }, 0);

  console.log(`✓ ${OUT} (${templateNames.length} templates, ${totalFiles} files)`);
}

main().catch((err) => {
  console.error(`✗ template manifest 빌드 실패: ${err.message}`);
  process.exit(1);
});
